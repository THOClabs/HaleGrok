# floquet.csv
# ---------------------------------------------------------------------------

def sorted_monodromy_eigenvalues(monodromy):
    """Eigenvalues sorted by |lambda| desc, ties by Re desc then Im desc."""
    eigenvalues = np.linalg.eigvals(monodromy)
    order = np.lexsort((-eigenvalues.imag, -eigenvalues.real, -np.abs(eigenvalues)))
    return eigenvalues[order]


def generate_floquet_lines(lyapunov_orbit):
    mu = MU_EARTH_MOON
    monodromy = compute_monodromy_matrix(lyapunov_orbit, mu, dt=1e-4)
    eigenvalues = sorted_monodromy_eigenvalues(monodromy)

    columns = ["mu", "x0", "vy0", "period"]
    values = [
        fmt(mu),
        fmt(lyapunov_orbit.initial_state[0]),
        fmt(lyapunov_orbit.initial_state[4]),
        fmt(lyapunov_orbit.period),
    ]
    for i, ev in enumerate(eigenvalues, start=1):
        columns.extend([f"ev{i}_re", f"ev{i}_im"])
        values.extend([fmt(ev.real), fmt(ev.imag)])

    header = base_header(
        [
            "# planar Lyapunov orbit about Earth-Moon L1; state = [x0,0,0,0,vy0,0]",
            "# monodromy from fixed-step RK4 STM propagation, dt=1e-4, one period",
            "# eigenvalues sorted by |lambda| descending; the trivial unit pair is a",
            "# defective Jordan block: compare ev columns with abs tolerance 1e-5",
        ]
    )
    return header + [",".join(columns)] + [",".join(values)]


