def generate_all():
    """Regenerate every reference file in memory: {filename: [lines]}."""
    lyapunov_orbit = find_l1_lyapunov_orbit()
    return {
        "lagrange_points.csv": generate_lagrange_lines(),
        "trajectories.csv": generate_trajectory_lines(lyapunov_orbit),
        "floquet.csv": generate_floquet_lines(lyapunov_orbit),
    }


def write_all(files):
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    for name, lines in files.items():
        path = DATA_DIR / name
        path.write_text("\n".join(lines) + "\n")
        print(f"wrote {path.relative_to(REPO_ROOT)} ({len(lines)} lines)")


def _tolerances_for(filename, column):
    if filename == "floquet.csv" and column.startswith("ev"):
        return EV_REL_TOL, EV_ABS_FLOOR
    if filename == "trajectories.csv":
        if column == "jacobi_drift":
            return TRAJ_REL_TOL, DRIFT_ABS_FLOOR
        return TRAJ_REL_TOL, TRAJ_ABS_FLOOR
    return REL_TOL, ABS_FLOOR


def _compare_file(filename, expected_lines, actual_lines, report):
    """Compare regenerated lines against committed lines. Appends diffs to report."""
    ok = True
    exp_comments = [line for line in expected_lines if line.startswith("# ")]
    act_comments = [line for line in actual_lines if line.startswith("# ")]
    if exp_comments != act_comments:
        report.append(f"{filename}: comment header mismatch")
        report.append(f"  committed : {act_comments}")
        report.append(f"  regenerated: {exp_comments}")
        ok = False

    exp_data = [line for line in expected_lines if not line.startswith("# ")]
    act_data = [line for line in actual_lines if not line.startswith("# ")]
    if not act_data or not exp_data:
        report.append(f"{filename}: missing data section")
        return False
    if exp_data[0] != act_data[0]:
        report.append(f"{filename}: column header mismatch")
        report.append(f"  committed : {act_data[0]}")
        report.append(f"  regenerated: {exp_data[0]}")
        return False
    columns = exp_data[0].split(",")
    if len(exp_data) != len(act_data):
        report.append(
            f"{filename}: row count mismatch (committed {len(act_data) - 1}, "
            f"regenerated {len(exp_data) - 1})"
        )
        return False

    for row_idx, (exp_row, act_row) in enumerate(zip(exp_data[1:], act_data[1:]), start=1):
        exp_fields = exp_row.split(",")
        act_fields = act_row.split(",")
        if len(exp_fields) != len(act_fields):
            report.append(f"{filename} row {row_idx}: field count mismatch")
            ok = False
            continue
        for col, exp_f, act_f in zip(columns, exp_fields, act_fields):
            try:
                exp_v = float(exp_f)
                act_v = float(act_f)
            except ValueError:
                if exp_f != act_f:
                    report.append(
                        f"{filename} row {row_idx} col {col}: "
                        f"'{act_f}' (committed) != '{exp_f}' (regenerated)"
                    )
                    ok = False
                continue
            rel_tol, abs_floor = _tolerances_for(filename, col)
            diff = abs(exp_v - act_v)
            limit = max(rel_tol * abs(exp_v), abs_floor)
            if diff > limit:
                report.append(
                    f"{filename} row {row_idx} col {col}: committed={act_f} "
                    f"regenerated={exp_f} |diff|={diff:.3e} > tol={limit:.3e}"
                )
                ok = False
    return ok


def check_all(files):
    report = []
    all_ok = True
    for name, expected_lines in files.items():
        path = DATA_DIR / name
        if not path.is_file():
            report.append(f"{name}: missing committed file {path}")
            all_ok = False
            continue
        actual_lines = path.read_text().splitlines()
        if not _compare_file(name, expected_lines, actual_lines, report):
            all_ok = False

    if all_ok:
        print(f"check OK: {len(files)} reference files match regenerated values")
        print(f"  tolerances: rel {REL_TOL:g} / abs floor {ABS_FLOOR:g}"
              f" (eigenvalue columns: rel {EV_REL_TOL:g} / abs floor {EV_ABS_FLOOR:g})")
        return 0
    print("check FAILED:")
    for line in report:
        print("  " + line)
    return 1


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    parser.add_argument(
        "--check",
        action="store_true",
        help="regenerate in memory and compare against committed CSVs (CI drift gate)",
    )
    args = parser.parse_args(argv)

    files = generate_all()
    if args.check:
        return check_all(files)
    write_all(files)
    return 0


if __name__ == "__main__":
    sys.exit(main())
