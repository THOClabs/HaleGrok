def trajectory_cases(lyapunov_orbit):
    """Well-conditioned, non-chaotic Earth-Moon test arcs (t = 2.0)."""
    mu = MU_EARTH_MOON
    return [
        # The corrected L1 Lyapunov orbit itself (bounded, periodic).
        ("l1_lyapunov", lyapunov_orbit.initial_state.copy()),
        # Distant retrograde orbit seed about the Moon (strongly stable
        # region); small z offset exercises the out-of-plane dynamics.
        ("dro_seed", np.array([1.0 - mu - 0.1, 0.0, 0.005, 0.0, 0.5, 0.0])),
        # Low prograde orbit about the Moon (near two-body regime).
        ("low_prograde_moon", np.array([1.0 - mu - 0.03, 0.0, 0.0, 0.0, -0.606, 0.0])),
        # Small zero-velocity libration displacement from L4 (stable for
        # Earth-Moon since mu < Routh critical ratio).
        ("l4_libration", np.array([0.5 - mu + 0.01, np.sqrt(3.0) / 2.0, 0.0, 0.0, 0.0, 0.0])),
    ]


def generate_trajectory_lines(lyapunov_orbit):
    mu = MU_EARTH_MOON
    columns = [
        "case", "mu", "x0", "y0", "z0", "vx0", "vy0", "vz0", "t_final",
        "xf", "yf", "zf", "vxf", "vyf", "vzf", "jacobi_drift",
    ]
    rows = []
    for name, state0 in trajectory_cases(lyapunov_orbit):
        result = propagate(
            state0, (0.0, TRAJECTORY_T_FINAL), mu, method="RK45", tol=TRAJECTORY_TOL
        )
        if not result.success:
            raise RuntimeError(f"propagation failed for case {name}: {result.message}")
        final = result.y[-1, :6]
        drift = float(np.max(np.abs(result.jacobi - result.jacobi[0])))
        rows.append(
            [name, fmt(mu)]
            + [fmt(v) for v in state0]
            + [fmt(TRAJECTORY_T_FINAL)]
            + [fmt(v) for v in final]
            + [fmt(drift)]
        )
    header = base_header(
        [
            "# oracle adaptive RK45 (scipy solve_ivp), rtol=atol=1e-12, Earth-Moon frame",
            "# jacobi_drift = max |C(t) - C(0)| along the arc",
        ]
    )
    return header + [",".join(columns)] + [",".join(r) for r in rows]


